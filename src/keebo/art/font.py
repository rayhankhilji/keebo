def _parse(src: str) -> Dict[str, List[str]]:
    out: Dict[str, List[str]] = {" ": ["..", "..", "..", "..", ".."]}
    for line in src.strip().splitlines():
        ch, *rows = line.split(" ")
        out[ch] = rows
    return out


